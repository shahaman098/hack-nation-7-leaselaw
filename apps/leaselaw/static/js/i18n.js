export function t(lang, key) {
  return STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
}

export function categoryLabel(lang, cat) {
  if (!cat) return "";
  const key = `category_${cat}`;
  return t(lang, key) || cat.replace(/_/g, " ");
}

export function resultLabel(lang, result) {
  const map = {
    applies: "applies",
    unknown: "unknown",
    superseded: "superseded",
    not_yet_effective: "notYet",
    pending: "pending",
    failed: "failed",
  };
  const k = map[result] || "applies";
  return t(lang, k);
}
